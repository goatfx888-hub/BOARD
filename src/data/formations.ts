export const getFormationById = (id?: string): Formation => {
  if (!id) return FORMATIONS[0];
  const normalized = id.trim().toLowerCase();
  return (
    FORMATIONS.find((f) => f.id.toLowerCase() === normalized) ||
    FORMATIONS.find((f) => f.id.toLowerCase().startsWith(normalized)) ||
    FORMATIONS.find((f) => f.name.toLowerCase().includes(normalized)) ||
    FORMATIONS[0]
  );
};
